// `ucm dev <app>`: serve a browser app straight from the codebase, with server functions called by hash.
//
// Vite serves the app's modules from .ucm/cache. A plugin swaps every component that has to run on the server for
// a stub module whose exports call it by hash (`POST /__ucm/rpc/<hash>`), so server code never reaches the
// browser. The same process answers those calls by importing the real module, but only for the hashes the app
// actually calls (its endpoints), since anything the browser can reach is a public endpoint.
import fs from "node:fs";
import path from "node:path";
import type http from "node:http";
import { pathToFileURL } from "node:url";
import type { Plugin } from "vite";
import { exportId, shortHash } from "@ucm/core";
import { materialize, writeIfChanged } from "@ucm/loader";
import type { Codebase } from "./codebase.ts";
import { codecSource, decode, encode } from "./codec.ts";
import { Placement, type AppPlan } from "./placement.ts";
import { bold, dim, green, red, yellow } from "./style.ts";

const RUNTIME = "virtual:ucm-runtime";
const CODEC = "virtual:ucm-codec";
const STUB = "\0ucm-stub:";
const HASH_FILE = /(?:^|\/)([a-z2-7]{52})\.ts$/;

const runtimeSource = `import { encode, decode } from ${JSON.stringify(CODEC)};

/** A function that runs on the server, called by hash. */
export function remote(hash, name, callable) {
  const fn = async (...args) => {
    if (!callable) throw new Error(name + " runs on the server and this app doesn't call it from the browser");
    let res;
    try {
      res = await fetch("/__ucm/rpc/" + hash, { method: "POST", headers: { "content-type": "application/json" }, body: encode(args, "arguments to " + name) });
    } catch (e) {
      throw new Error(name + ": the server is unreachable (" + e.message + ")");
    }
    const body = decode(await res.text());
    if (!res.ok) {
      const err = new Error(body && body.message ? body.message : res.statusText);
      err.name = body && body.name ? body.name : "RemoteError";
      throw err;
    }
    return body;
  };
  Object.defineProperty(fn, "name", { value: name });
  return fn;
}
`;

interface DevState {
  hash: string;
  plan: AppPlan;
  head: string;
}

const escapeHtml = (s: string) => s.replace(/[&<>]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" })[c]!);

export async function dev(cb: Codebase, appName: string, port: number): Promise<{ url: string; close: () => Promise<void> }> {
  const { createServer } = await import("vite");
  const webDir = path.join(cb.lay.ucmDir, "web");
  fs.mkdirSync(webDir, { recursive: true });
  writeIfChanged(
    path.join(webDir, "index.html"),
    `<!doctype html>\n<html>\n  <head><meta charset="utf-8" /><title>${escapeHtml(appName)}</title></head>\n  <body>\n    <div id="app"></div>\n    <script type="module" src="/entry.ts"></script>\n  </body>\n</html>\n`,
  );

  const plan = (): DevState => {
    const hash = cb.lookupOne(appName, "value");
    materialize([hash], cb.source(), cb.lay); // the whole closure, server side included, with npm packages
    const p = new Placement(cb).planApp(hash);
    const rec = cb.store.getDef(hash)!;
    const entry = p.errors.length
      ? `// ${appName} can't run in the browser yet\ndocument.body.innerHTML = ${JSON.stringify(`<pre style="color:#b00;white-space:pre-wrap;font:14px ui-monospace,monospace;padding:1em">${escapeHtml(p.errors.join("\n\n"))}</pre>`)};\n`
      : `// generated by ucm dev: ${appName} ${rec.hash}\nimport { ${exportId(rec.hash)} as main } from "../cache/${rec.componentHash}.ts";\nconst app: unknown = main;\nif (typeof app === "function") await app();\n`;
    writeIfChanged(path.join(webDir, "entry.ts"), entry);
    return { hash, plan: p, head: `${cb.store.branch().name}:${cb.store.logHead()}` };
  };
  let state = plan();

  const rpc = async (req: http.IncomingMessage, res: http.ServerResponse, next: () => void) => {
    const m = /^\/__ucm\/rpc\/([a-z2-7]{52})$/.exec((req.url ?? "").split("?")[0]!);
    if (!m) return next();
    const started = performance.now();
    const hash = m[1]!;
    const name = cb.displayRef(`#${hash}`);
    const send = (status: number, body: unknown) => {
      let text: string;
      try {
        text = encode(body, `result of ${name}`);
      } catch (e) {
        status = 500;
        text = encode({ name: "TypeError", message: (e as Error).message });
      }
      res.statusCode = status;
      res.setHeader("content-type", "application/json");
      res.end(text);
      const mark = status === 200 ? green(String(status)) : red(String(status));
      console.log(`  ${dim("→")} ${name} ${mark} ${dim(`${Math.round(performance.now() - started)}ms`)}`);
    };
    const origin = req.headers.origin;
    if (origin && new URL(origin).host !== req.headers.host) return send(403, { name: "RemoteError", message: "cross-origin call refused" });
    if (req.method !== "POST") return send(405, { name: "RemoteError", message: "use POST" });
    if (!state.plan.endpoints.has(hash)) return send(403, { name: "RemoteError", message: `${shortHash(hash)} isn't a server function this app calls` });
    let text = "";
    for await (const chunk of req) {
      text += chunk;
      if (text.length > 16 * 1024 * 1024) return send(413, { name: "RemoteError", message: "arguments too large" });
    }
    let args: unknown;
    try {
      args = decode(text);
    } catch {
      return send(400, { name: "RemoteError", message: "malformed arguments" });
    }
    if (!Array.isArray(args)) return send(400, { name: "RemoteError", message: "arguments must be a list" });
    try {
      const rec = cb.store.getDef(hash)!;
      // a hash names immutable code, so Node's module cache can never serve a stale version of it
      const mod = (await import(pathToFileURL(path.join(cb.lay.cacheDir, `${rec.componentHash}.ts`)).href)) as Record<string, (...a: unknown[]) => unknown>;
      send(200, await mod[exportId(hash)]!(...args));
    } catch (e) {
      const err = e as Error;
      send(500, { name: err?.name ?? "Error", message: err?.message ?? String(e) });
    }
  };

  const plugin: Plugin = {
    name: "ucm",
    // ahead of Vite's own resolver: server components must be swapped for stubs before they are resolved as files
    enforce: "pre",
    resolveId(source) {
      if (source === RUNTIME) return "\0" + RUNTIME;
      if (source === CODEC) return "\0" + CODEC;
      const m = HASH_FILE.exec(source);
      // server components reach the browser only as stubs
      if (m && /^\.\.?\//.test(source) && state.plan.stubbed.has(m[1]!)) return STUB + m[1];
      return null;
    },
    load(id) {
      if (id === "\0" + RUNTIME) return runtimeSource;
      if (id === "\0" + CODEC) return codecSource();
      if (!id.startsWith(STUB)) return null;
      const members = cb.store.componentMembers(id.slice(STUB.length));
      return [
        `import { remote } from ${JSON.stringify(RUNTIME)};`,
        ...members.map((m) => `export const ${exportId(m.hash)} = remote(${JSON.stringify(m.hash)}, ${JSON.stringify(m.nameHint)}, ${state.plan.endpoints.has(m.hash)});`),
      ].join("\n");
    },
    configureServer(server) {
      server.middlewares.use(rpc);
    },
  };

  const server = await createServer({
    configFile: false,
    root: webDir,
    logLevel: "warn",
    clearScreen: false,
    appType: "spa",
    plugins: [plugin],
    server: { port, host: "127.0.0.1", fs: { allow: [cb.lay.ucmDir] } },
  });
  await server.listen();
  const url = server.resolvedUrls?.local[0] ?? `http://127.0.0.1:${port}/`;

  const report = (s: DevState) => {
    if (s.plan.errors.length) {
      console.log(red(`\n  ${appName} can't run in the browser yet:`));
      for (const e of s.plan.errors) console.log(red(`    ${e}`));
      return;
    }
    console.log(`  browser  ${s.plan.browser.size} definition(s)`);
    const endpoints = [...s.plan.endpoints].map((h) => `${cb.displayRef(`#${h}`)} ${dim(shortHash(h))}`);
    console.log(`  server   ${endpoints.length ? `${endpoints.length} function(s) the browser calls by hash: ${endpoints.join(", ")}` : dim("nothing (the app runs entirely in the browser)")}`);
  };
  console.log(`${bold("ucm dev")} ${appName} ${dim(shortHash(state.hash))}\n  url      ${url}`);
  report(state);

  // Reload the browser when the codebase changes under the app (`ucm update`, `mv`, `pull`, ... in another
  // shell). One command can change names in several steps (an update, then its propagation), so act only once the
  // codebase has stayed the same for a whole poll.
  let pending: string | undefined;
  const poll = setInterval(() => {
    cb.store.forgetBranch();
    const head = `${cb.store.branch().name}:${cb.store.logHead()}`;
    if (head === state.head) return;
    if (head !== pending) {
      pending = head;
      return;
    }
    try {
      const before = state.hash;
      state = plan();
      server.moduleGraph.invalidateAll();
      server.ws.send({ type: "full-reload" });
      console.log(`\n${yellow("reloaded")} ${appName} ${dim(before === state.hash ? "(names changed)" : `${shortHash(before)} → ${shortHash(state.hash)}`)}`);
      report(state);
    } catch (e) {
      console.log(red(`  ${(e as Error).message}`));
      state.head = head;
    }
  }, 400);

  return {
    url,
    close: async () => {
      clearInterval(poll);
      await server.close();
    },
  };
}
